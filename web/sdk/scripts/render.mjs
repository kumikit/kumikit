// Renders src/generated.ts from the newest version in api/. Shared by the generator and
// the staleness test.
import { readFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const api = fileURLToPath(new URL('../api/', import.meta.url));

/** Version directories in api/, oldest first. */
export function versions() {
  const parse = (v) => v.split('.').map(Number);
  return readdirSync(api, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort((a, b) => {
      const [x, y] = [parse(a), parse(b)];
      return x[0] - y[0] || x[1] - y[1] || x[2] - y[2];
    });
}

export function render() {
  const latest = versions().at(-1);
  const read = (f) => JSON.parse(readFileSync(`${api}${latest}/${f}`, 'utf8'));
  const slots = read('slots.json').slots;
  const tokens = read('tokens.json').tokens;
  const union = (xs) => xs.map((x) => `\n  | '${x}'`).join('');
  return `// Generated from web/sdk/api/${latest}/ by \`npm run generate -w @kumikit/ui-sdk\`.
// Do not edit this file manually.

/** The UI SDK version these lists belong to. */
export const SDK_VERSION = '${latest}';

/** A slot where UI plugins contribute (\`docs/spec/07-ui-plugins.md#slots\`). */
export type Slot =${union(slots.map((s) => s.id))};

/** Every slot, in the published order. */
export const SLOTS: readonly Slot[] = [${slots.map((s) => `'${s.id}'`).join(', ')}];

/** A design token (\`docs/spec/08-themes.md#tokens\`). */
export type TokenName =${union(tokens.map((t) => t.name))};

/** The value type of a token. */
export type TokenType = ${[...new Set(tokens.map((t) => `'${t.type}'`))].join(' | ')};

/** Every token with its group and type, in the published order. */
export const TOKENS: readonly { name: TokenName; group: string; type: TokenType }[] = [
${tokens.map((t) => `  { name: '${t.name}', group: '${t.group}', type: '${t.type}' },`).join('\n')}
];
`;
}
