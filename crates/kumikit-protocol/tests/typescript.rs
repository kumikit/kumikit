//! Generates `@kumikit/protocol` (TypeScript) from the Rust types and fails when the files
//! in `web/protocol/` are stale. `KUMIKIT_BLESS=1 cargo test -p kumikit-protocol` rewrites
//! them. See ADR 0008.

// Integration-test crate: clippy's allow-*-in-tests does not cover helper functions.
#![allow(clippy::unwrap_used, clippy::expect_used)]

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use kumikit_protocol::error::{ErrorCode, RpcError};
use kumikit_protocol::jsonrpc::{Request, ServerMessage};
use kumikit_protocol::methods::{self, Method, MethodVisitor, NotificationMethod};
use kumikit_protocol::{PROTOCOL_VERSION, ThreadEvent};
use ts_rs::{Config, TS};

/// TypeScript version used to type-check the generated package (CI and locally).
const TYPESCRIPT_VERSION: &str = "7.0.2";

fn config(out: &Path) -> Config {
    // JSON numbers are never `bigint`; protocol integers stay below 2^53.
    Config::new().with_large_int("number").with_out_dir(out)
}

struct Exporter<'a> {
    cfg: &'a Config,
    methods: Vec<(&'static str, String, String)>,
    notifications: Vec<(&'static str, String)>,
}

impl MethodVisitor for Exporter<'_> {
    fn method<M: Method>(&mut self) {
        <M::Params as TS>::export_all(self.cfg).expect("export params");
        <M::Result as TS>::export_all(self.cfg).expect("export result");
        self.methods.push((
            M::NAME,
            <M::Params as TS>::name(self.cfg),
            <M::Result as TS>::name(self.cfg),
        ));
    }

    fn notification<N: NotificationMethod>(&mut self) {
        <N::Params as TS>::export_all(self.cfg).expect("export notification");
        self.notifications
            .push((N::NAME, <N::Params as TS>::name(self.cfg)));
    }
}

const HEADER: &str = "// Generated from crates/kumikit-protocol by `KUMIKIT_BLESS=1 cargo test -p kumikit-protocol`.\n// Do not edit this file manually.\n";

/// Writes the whole `web/protocol` package into `root`.
fn generate(root: &Path) {
    let src = root.join("src");
    fs::create_dir_all(&src).unwrap();
    let cfg = config(&src);

    let mut exporter = Exporter {
        cfg: &cfg,
        methods: Vec::new(),
        notifications: Vec::new(),
    };
    methods::visit_all(&mut exporter);
    // Types clients need that no method names directly.
    Request::export_all(&cfg).unwrap();
    ServerMessage::export_all(&cfg).unwrap();
    RpcError::export_all(&cfg).unwrap();
    ErrorCode::export_all(&cfg).unwrap();
    ThreadEvent::export_all(&cfg).unwrap();

    let mut imports: Vec<&str> = Vec::new();
    for (_, p, r) in &exporter.methods {
        imports.push(p);
        imports.push(r);
    }
    for (_, p) in &exporter.notifications {
        imports.push(p);
    }
    imports.sort_unstable();
    imports.dedup();

    let mut m = String::from(HEADER);
    for name in &imports {
        writeln!(m, "import type {{ {name} }} from \"./{name}\";").unwrap();
    }
    writeln!(
        m,
        "\n/** Protocol version spoken by this package, `MAJOR.MINOR`. */"
    )
    .unwrap();
    writeln!(m, "export const PROTOCOL_VERSION = \"{PROTOCOL_VERSION}\";").unwrap();
    writeln!(
        m,
        "\n/** Every request method with its params and result types. */"
    )
    .unwrap();
    writeln!(m, "export type Methods = {{").unwrap();
    for (name, p, r) in &exporter.methods {
        writeln!(m, "  \"{name}\": {{ params: {p}; result: {r} }};").unwrap();
    }
    writeln!(
        m,
        "}};\n\n/** Every notification the core sends, with its params type. */"
    )
    .unwrap();
    writeln!(m, "export type Notifications = {{").unwrap();
    for (name, p) in &exporter.notifications {
        writeln!(m, "  \"{name}\": {p};").unwrap();
    }
    writeln!(m, "}};\n\nexport type MethodName = keyof Methods;").unwrap();
    writeln!(m, "export type NotificationName = keyof Notifications;").unwrap();
    fs::write(src.join("methods.ts"), m).unwrap();

    // index.ts re-exports every generated module.
    let mut modules: Vec<String> = read_tree(&src)
        .into_keys()
        .map(|p| p.to_string_lossy().replace('\\', "/"))
        .filter_map(|f| f.strip_suffix(".ts").map(str::to_owned))
        .filter(|f| f != "methods")
        .collect();
    modules.sort_unstable();
    let mut index = String::from(HEADER);
    index.push_str("export * from \"./methods\";\n");
    for module in modules {
        writeln!(index, "export type * from \"./{module}\";").unwrap();
    }
    fs::write(src.join("index.ts"), index).unwrap();

    let version = env!("CARGO_PKG_VERSION");
    fs::write(
        root.join("package.json"),
        format!(
            r#"{{
  "name": "@kumikit/protocol",
  "version": "{version}",
  "description": "Kumikit client–core protocol types, generated from crates/kumikit-protocol. Do not edit.",
  "license": "MIT",
  "private": true,
  "type": "module",
  "types": "./src/index.ts",
  "exports": {{ ".": "./src/index.ts" }},
  "scripts": {{ "check": "tsc --noEmit -p ." }},
  "devDependencies": {{ "typescript": "{TYPESCRIPT_VERSION}" }}
}}
"#
        ),
    )
    .unwrap();
    fs::write(
        root.join("tsconfig.json"),
        r#"{
  "compilerOptions": {
    "strict": true,
    "noEmit": true,
    "target": "es2022",
    "module": "esnext",
    "moduleResolution": "bundler",
    "isolatedModules": true,
    "verbatimModuleSyntax": true,
    "skipLibCheck": true
  },
  "include": ["src"]
}
"#,
    )
    .unwrap();
}

fn read_tree(root: &Path) -> BTreeMap<PathBuf, String> {
    let mut out = BTreeMap::new();
    let mut stack = vec![root.to_path_buf()];
    while let Some(dir) = stack.pop() {
        let Ok(entries) = fs::read_dir(&dir) else {
            continue;
        };
        for entry in entries {
            let path = entry.unwrap().path();
            let rel = path.strip_prefix(root).unwrap().to_path_buf();
            if rel.starts_with("node_modules") || rel.ends_with("package-lock.json") {
                continue;
            }
            if path.is_dir() {
                stack.push(path);
            } else {
                // Normalize line endings so a Windows checkout with autocrlf compares equal.
                out.insert(
                    rel,
                    fs::read_to_string(&path).unwrap().replace("\r\n", "\n"),
                );
            }
        }
    }
    out
}

#[test]
fn generated_typescript_is_current() {
    let repo = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let target = repo.join("web/protocol");
    let tmp = tempfile::tempdir().unwrap();
    generate(tmp.path());
    let expected = read_tree(tmp.path());

    if std::env::var_os("KUMIKIT_BLESS").is_some() {
        let _ = fs::remove_dir_all(target.join("src"));
        for (rel, content) in &expected {
            let path = target.join(rel);
            fs::create_dir_all(path.parent().unwrap()).unwrap();
            fs::write(path, content).unwrap();
        }
        return;
    }

    let actual = read_tree(&target);
    let mut problems = Vec::new();
    for (rel, content) in &expected {
        match actual.get(rel) {
            None => problems.push(format!("missing {}", rel.display())),
            Some(a) if a != content => problems.push(format!("stale {}", rel.display())),
            Some(_) => {}
        }
    }
    for rel in actual.keys().filter(|k| !expected.contains_key(*k)) {
        problems.push(format!("unexpected {}", rel.display()));
    }
    assert!(
        problems.is_empty(),
        "web/protocol is out of date ({}).\nRun `KUMIKIT_BLESS=1 cargo test -p kumikit-protocol` and commit the result.",
        problems.join(", ")
    );
}
