//! Consolidated integration test harness for `kumikit-shell` (`remote` stays separate
//! because docs invoke `cargo test -p kumikit-shell --test remote -- --ignored`).

#![allow(clippy::unwrap_used, clippy::expect_used)]

mod local_core;
mod registry;

#[test]
fn main_capability_allows_every_non_test_command() {
    let manifest_dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
    let build_rs = std::fs::read_to_string(manifest_dir.join("build.rs")).unwrap();
    let main_cap = std::fs::read_to_string(manifest_dir.join("capabilities/main.json")).unwrap();
    let cap_json: serde_json::Value = serde_json::from_str(&main_cap).unwrap();
    let perms: std::collections::BTreeSet<&str> = cap_json["permissions"]
        .as_array()
        .unwrap()
        .iter()
        .filter_map(|v| v.as_str())
        .collect();

    // Extract every quoted command name in `.commands(&[...])`.
    let commands_block = build_rs
        .split(".commands(&[")
        .nth(1)
        .unwrap()
        .split("])")
        .next()
        .unwrap();
    let mut seen = 0usize;
    for line in commands_block.lines() {
        let trimmed = line.trim().trim_end_matches(',');
        if let Some(cmd) = trimmed.strip_prefix('"').and_then(|s| s.strip_suffix('"')) {
            seen += 1;
            if cmd == "test_report" {
                continue;
            }
            let allow = format!("allow-{}", cmd.replace('_', "-"));
            assert!(
                perms.contains(allow.as_str()),
                "command `{cmd}` is declared in build.rs but missing `{allow}` in capabilities/main.json"
            );
            let auto = manifest_dir.join(format!("permissions/autogenerated/{cmd}.toml"));
            assert!(
                auto.is_file(),
                "missing autogenerated permission file {}",
                auto.display()
            );
        }
    }
    assert!(seen > 0, "expected commands in build.rs");
    assert!(
        perms.contains("allow-pick-attachments"),
        "pick_attachments must be allowed in capabilities/main.json"
    );
}
